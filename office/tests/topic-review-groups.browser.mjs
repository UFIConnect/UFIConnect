import assert from 'node:assert/strict';
import { fileURLToPath } from 'node:url';
import { chromium } from 'playwright';
import { createServer } from 'vite';

const officeRoot=fileURLToPath(new URL('../',import.meta.url));
const server=await createServer({root:officeRoot,server:{host:'127.0.0.1',port:4182,strictPort:true}});
const checks=[],pageErrors=[];
let browser;
try {
  await server.listen();
  browser=await chromium.launch({...process.env.PLAYWRIGHT_CHANNEL?{channel:process.env.PLAYWRIGHT_CHANNEL}:process.platform==='win32'?{channel:'msedge'}:{},headless:true});
  const page=await browser.newPage({viewport:{width:1440,height:1000}});
  page.setDefaultTimeout(15000);
  page.on('pageerror',error=>pageErrors.push(error.message));
  await page.goto('http://127.0.0.1:4182/tests/topic-review-groups.html');
  await page.getByLabel('Refresh topic and agent status every 15 seconds').uncheck();
  const held=page.getByRole('region',{name:'Held post review'});
  await held.getByRole('button',{name:'View held posts',exact:true}).click();
  await page.waitForFunction(()=>window.topicReviewFixture.refreshPending.length===1);
  assert.match(await held.innerText(),/500/);
  assert.match(await held.innerText(),/38,000/);
  assert.equal(await page.evaluate(()=>window.topicReviewFixture.batches.length),0);
  await page.evaluate(()=>window.topicReviewFixture.refreshPending.shift()());
  await held.getByRole('button',{name:'Review Python group',exact:true}).waitFor();
  assert.equal(await page.evaluate(()=>window.topicReviewFixture.refreshes),2);
  checks.push('automatic grouping shows partial 500-of-38,000 progress and continues without assigning any posts');

  const find=held.getByLabel('Find topics or posts',{exact:true});
  await find.fill('Python');
  await page.waitForFunction(()=>window.topicReviewFixture.requests.some(row=>row.path==='/office/topic-review/groups'&&row.query.q==='Python'));
  await held.getByRole('button',{name:'Review Python group',exact:true}).waitFor();
  assert.equal(await held.getByRole('button',{name:'Review JavaScript group',exact:true}).count(),0);
  await find.fill('');
  await held.getByRole('button',{name:'Review JavaScript group',exact:true}).waitFor();
  await held.getByRole('combobox',{name:/^Source/}).selectOption('devto');
  await page.waitForFunction(()=>window.topicReviewFixture.requests.some(row=>row.path==='/office/topic-review/groups'&&row.query.source==='devto'));
  await held.getByRole('combobox',{name:/^Source/}).selectOption('');
  await held.getByRole('button',{name:'Review Python group',exact:true}).click();
  // The previous unfiltered page can remain visible until the group request starts.
  // Wait for the grouped response before inspecting its selection controls.
  await held.getByText('32 matching posts',{exact:true}).waitFor();
  const postSelection=held.getByLabel('Select all posts on this page',{exact:true});
  await postSelection.waitFor();
  assert.equal(await held.getByRole('checkbox').count(),26);
  assert.equal(await page.evaluate(()=>window.topicReviewFixture.requests.filter(row=>row.path==='/office/topic-review').at(-1).query.group),'a'.repeat(64));
  await postSelection.check();
  assert.equal(await held.getByRole('checkbox').filter({visible:true}).count(),26);
  await held.getByRole('button',{name:'Next page',exact:true}).click();
  await held.getByLabel('Select Python Django tutorial 32',{exact:true}).waitFor();
  assert.equal(await held.locator('input[type=checkbox]:checked').count(),0);
  await postSelection.check();
  assert.equal(await held.locator('input[type=checkbox]:checked').count(),8);
  await postSelection.uncheck();
  await held.getByRole('button',{name:'Previous page',exact:true}).click();
  await held.getByLabel('Select Python Django tutorial 1',{exact:true}).check();
  await held.getByLabel('Select Python Django tutorial 3',{exact:true}).check();
  checks.push('topic/post and source searches reach group queries; opening a group preserves its filter and page selection covers only visible posts');

  const picker=held.getByLabel('Topic for selected posts',{exact:true});
  await picker.fill('automation');
  const choose=held.getByRole('group',{name:'Topic for selected posts choices'});
  await choose.getByRole('button',{name:'Python',exact:true}).waitFor();
  assert.equal(await held.getByRole('button',{name:'Assign 2 selected posts',exact:true}).isDisabled(),true);
  await choose.getByRole('button',{name:'Python',exact:true}).click();
  await held.getByRole('button',{name:'Assign 2 selected posts',exact:true}).click();
  await page.waitForFunction(()=>window.topicReviewFixture.assigned===2);
  const submitted=await page.evaluate(()=>window.topicReviewFixture.batches[0]);
  assert.deepEqual(submitted,{items:[{id:'held-00',expectedVersion:'1'.padStart(64,'0')},{id:'held-02',expectedVersion:'3'.padStart(64,'0')}],topic:'Python',confirmed:true});
  checks.push('visible topic search matches subtopics; batch assignment contains exactly the two selected IDs and their reviewed versions');

  await held.getByLabel('Select Python Django tutorial 2',{exact:true}).check();
  await picker.fill('Python');
  await page.evaluate(()=>{window.topicReviewFixture.batchMode='conflict';});
  await held.getByRole('button',{name:'Assign 1 selected posts',exact:true}).click();
  await held.getByText('Posts that need another review',{exact:true}).click();
  await held.getByText('The held post changed since it was opened. Refresh its preview and review the latest content.',{exact:false}).waitFor();
  assert.equal(await page.evaluate(()=>window.topicReviewFixture.assigned),2);
  checks.push('stale batch conflicts remain visible and leave preserved posts unassigned');

  await held.getByRole('button',{name:'All topic groups',exact:true}).click();
  await held.getByRole('button',{name:'Review JavaScript group',exact:true}).click();
  await held.getByRole('button',{name:'Select all posts in this group',exact:true}).click();
  await held.getByRole('heading',{name:'205 posts selected',exact:true}).waitFor();
  assert.equal(await page.evaluate(()=>window.topicReviewFixture.requests.filter(row=>row.path.includes('/members')).length),1);
  checks.push('whole-group selection snapshots all 205 members across pages before assignment');
  await page.evaluate(()=>{window.topicReviewFixture.batchMode='hold';});
  await held.getByRole('button',{name:'Assign 205 selected posts',exact:true}).click();
  await page.waitForFunction(()=>window.topicReviewFixture.batchPending.length===1);
  await page.evaluate(()=>{window.dispatchEvent(new Event('office-token-changed'));window.topicReviewFixture.batchPending.shift()();});
  await page.waitForFunction(()=>!document.querySelector('.unknown-topic-review input[type=checkbox]:checked'));
  assert.equal(await held.getByText('100 posts assigned to JavaScript.',{exact:false}).count(),0);
  await page.waitForTimeout(1200);
  assert.equal(await page.evaluate(()=>window.topicReviewFixture.batches.length),3);
  assert.equal(await page.evaluate(()=>window.topicReviewFixture.batches.at(-1).items.length),100);
  checks.push('authentication changes clear protected selection, suppress a pending response and stop future 100-post batches');

  const topicSearch=page.getByLabel('Find a topic or subtopic',{exact:true});
  await topicSearch.fill('automation');
  const topicSection=page.getByRole('heading',{name:'Topics and subtopics',exact:true}).locator('..');
  await topicSection.getByRole('button',{name:'Python',exact:true}).waitFor();
  assert.equal(await topicSection.getByRole('button',{name:'JavaScript',exact:true}).count(),0);
  await topicSearch.fill('');
  assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),true);
  await page.screenshot({path:fileURLToPath(new URL('../../../grouped-review-desktop.png',import.meta.url)),fullPage:true});
  await page.setViewportSize({width:390,height:900});
  assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),true);
  await page.screenshot({path:fileURLToPath(new URL('../../../grouped-review-mobile.png',import.meta.url)),fullPage:true});
  await held.getByRole('button',{name:'Review Python group',exact:true}).click();
  await held.getByLabel('Select Python Django tutorial 2',{exact:true}).check();
  await picker.fill('automation');
  await held.getByRole('group',{name:'Topic for selected posts choices'}).getByRole('button',{name:'Python',exact:true}).waitFor();
  assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),true);
  await page.screenshot({path:fileURLToPath(new URL('../../../grouped-review-mobile-selection.png',import.meta.url)),fullPage:true});
  assert.deepEqual(pageErrors,[]);
  checks.push('topic coverage search matches subtopics; desktop 1440px and mobile 390px have no horizontal overflow or browser errors');
  console.log(JSON.stringify({passed:true,checks},null,2));
} finally {await browser?.close();await server.close();}
