import assert from 'node:assert/strict';
import path from 'node:path';
import { createRequire } from 'node:module';
import { fileURLToPath } from 'node:url';
import { chromium } from 'playwright';
import { createServer } from '../web/node_modules/vite/dist/node/index.js';
import { installAuditMember, auditNavigate } from './audit-session.mjs';
const require = createRequire(import.meta.url);
const { createAppHarness, member } = require('../backend/test-support/app-harness');
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const app = await createAppHarness(); app.seedUser(member('category-audit', { plan: 'pro' }));
const server = await createServer({ root: path.join(root, 'web'), configFile: path.join(root, 'web/vite.config.js'), envDir: false,
  define: { 'import.meta.env.VITE_API_URL': JSON.stringify('/api') },
  server: { host: '127.0.0.1', port: 5274, strictPort: false, proxy: { '/api': { target: app.base, rewrite: p => p.replace(/^\/api/, '') } } } });
let browser;
try {
  await server.listen(); browser = await chromium.launch({ channel: 'msedge' });
  const context = await browser.newContext({ viewport: { width: 390, height: 900 } });
  const page = await context.newPage(), events = [], errors = []; page.setDefaultTimeout(15000);
  page.on('pageerror', error => errors.push(error.message));
  await context.route('**/api/**', async route => {
    const req = route.request(), endpoint = new URL(req.url()).pathname.replace(/^\/api/, '');
    if (endpoint === '/analytics/pageview') {
      const body = req.postDataJSON(); assert.deepEqual(Object.keys(body), ['category']);
      assert.ok(!JSON.stringify(body).includes('PRIVATE')); assert.equal(req.headers().authorization, undefined);
      assert.equal(req.headers().referer, undefined); events.push(body.category);
      return route.fulfill({ status: 204 });
    }
    if (endpoint === '/social/platforms') return route.fulfill({ json: { platforms: {}, connected: {} } });
    if (endpoint === '/profile/social') return route.fulfill({ json: { connected: {} } });
    if (endpoint.startsWith('/office/feed/')) return route.fulfill({ json: { posts: [], hasMore: false, sourceErrors: {} } });
    if (endpoint === '/connected-inbox/notifications' || endpoint === '/connected-inbox/messages') return route.fulfill({ json: { notifications: [], conversations: [], sources: [{ source: 'bluesky', connected: true }] } });
    if (/events|stream/.test(endpoint)) return route.abort();
    return route.continue();
  });
  await installAuditMember(page, app, 'category-audit');
  await auditNavigate(page, server.resolvedUrls.local[0] + 'command-center?tab=accounts&secret=PRIVATE_VALUE');
  await page.getByRole('tabpanel', { name: 'Connected Accounts', exact: true }).waitFor();
  await page.waitForFunction(() => document.querySelector('[role="tab"][aria-selected="true"]')?.textContent.includes('Connected Accounts'));
  await page.waitForTimeout(150);
  assert.equal(events.filter(value => value === 'command_center_accounts').length, 1);
  await page.getByRole('tab', { name: 'Cross-Post', exact: true }).click();
  await page.getByRole('tabpanel', { name: 'Cross-Post', exact: true }).waitFor();
  await page.getByRole('tab', { name: 'Cross-Post', exact: true }).click();
  await page.getByRole('tab', { name: 'Connected Accounts', exact: true }).click();
  await page.getByRole('tabpanel', { name: 'Connected Accounts', exact: true }).waitFor();
  await page.waitForTimeout(150);
  assert.equal(events.filter(value => value === 'command_center_crosspost').length, 1);
  assert.equal(events.filter(value => value === 'command_center_accounts').length, 2);
  assert.equal(events.filter(value => value === 'command_center').length, 1, 'Tab query changes do not double count page entries');
  await auditNavigate(page, server.resolvedUrls.local[0] + 'how-it-works');
  await page.waitForTimeout(100);
  await page.goBack();
  await page.getByRole('tabpanel', { name: 'Connected Accounts', exact: true }).waitFor();
  await page.waitForTimeout(100);
  assert.equal(events.filter(value => value === 'command_center_accounts').length, 3, 'Returning to the same history entry counts a new tab visit');
  await page.goto(server.resolvedUrls.local[0] + 'videos');
  await page.getByRole('group', { name: 'Video feed mode', exact: true }).getByRole('button', { name: 'Following', exact: true }).click();
  await page.getByRole('button', { name: 'Filter videos', exact: true }).click();
  const mastodon = page.getByRole('button', { name: 'Mastodon', exact: true });
  await mastodon.click(); await mastodon.click(); await mastodon.click();
  await page.waitForTimeout(100);
  assert.equal(events.filter(value => value === 'video_mode_following').length, 1);
  assert.equal(events.filter(value => value === 'video_source_mastodon').length, 2, 'Deselecting and reselecting a source counts a new visit');
  await page.goto(server.resolvedUrls.local[0] + 'music');
  await page.getByRole('button', { name: 'Filter videos', exact: true }).click();
  await page.getByRole('button', { name: 'YouTube', exact: true }).click();
  await page.waitForTimeout(100);
  assert.equal(events.filter(value => value === 'music_mode_feed').length, 1);
  assert.equal(events.filter(value => value === 'music_source_youtube').length, 1);
  await page.goto(server.resolvedUrls.local[0] + 'notifications');
  await page.getByRole('group', { name: 'Notification filter', exact: true }).getByRole('button', { name: 'Unread', exact: true }).click();
  await page.getByLabel('Notification source', { exact: true }).selectOption('bluesky');
  await page.waitForTimeout(100);
  assert.equal(events.filter(value => value === 'notification_filter_unread').length, 1);
  assert.equal(events.filter(value => value === 'notification_source_bluesky').length, 1);
  await page.goto(server.resolvedUrls.local[0] + 'messages');
  await page.getByLabel('Message source', { exact: true }).selectOption('bluesky');
  await page.waitForTimeout(100);
  assert.equal(events.filter(value => value === 'message_source_bluesky').length, 1);
  await page.goto(server.resolvedUrls.local[0] + 'settings?tab=privacy&secret=PRIVATE_VALUE');
  await page.getByRole('heading', { name: 'Settings', exact: true }).waitFor(); await page.waitForTimeout(150);
  assert.equal(events.filter(value => value === 'settings_privacy').length, 1);
  assert.equal(events.filter(value => value === 'settings_account').length, 0, 'Requested tab is counted, not an unused initial default');
  const beforePrivate = events.length;
  await page.goto(server.resolvedUrls.local[0] + 'vault?secret=PRIVATE_VALUE'); await page.waitForTimeout(250);
  assert.equal(events.length, beforePrivate, 'Private Vault routes generate no counters');
  await page.goto(server.resolvedUrls.local[0] + 'how-it-works');
  await page.waitForTimeout(250);
  assert.equal(events.filter(value => value === 'how_it_works').length, 2);
  assert.deepEqual(errors, []);
  console.log('PASS category-only routes, CommandCenter/video/music/inbox tabs, source re-selection, StrictMode deduplication and Vault exclusion');
} finally { await browser?.close(); await server.close(); await app.close(); }
