  await button(page, 'Live Maps').click();
  await button(page, 'Grid').click();
  assert.equal(await page.getByRole('combobox', { name: /^Grid spacing/ }).locator('option').count(), 7);
  await page.getByRole('combobox', { name: /^Grid spacing/ }).selectOption('custom');
  const spacing = page.getByLabel('Custom grid spacing (degrees)');
  await spacing.fill('0');
  await spacing.blur();
  await page.getByRole('alert').filter({ hasText: 'Choose grid spacing' }).waitFor();
  await spacing.fill('0.007');
  await spacing.blur();
  await page.getByRole('combobox', { name: /^Grid spacing/ }).selectOption('detail');
  await page.getByLabel('Find grid cell by ID').fill('90001-180001');
  await button(page, 'Inspect cell ID').click();
  await page.getByRole('heading', { name: 'Inspected cell 90001-180001' }).waitFor();
  await page.getByLabel('Saved cell name').fill('Office block');
  await page.getByRole('textbox', { name: /^Cell note/ }).fill('North entrance');
  await button(page, 'Save selected cell').click();
  await page.getByRole('list', { name: 'Saved grid cells' }).getByText('Office block', { exact: true }).waitFor();
  await page.locator('[data-grid-overlay="saved"]').waitFor({ state: 'attached' });
  await page.getByText('Grid display', { exact: true }).click();
  await page.getByLabel('Show cell labels').check();
  await page.getByLabel('Grid line color').selectOption('cyan');
  await page.getByLabel('Grid line weight').selectOption('2');
  await page.getByLabel('Grid line opacity').selectOption('100');
  await page.getByLabel('Surrounding grid rings').selectOption('3');
  await page.locator('[data-movement-grid]').waitFor({ state: 'attached' });
