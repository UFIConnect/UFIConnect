import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { createRequire } from 'node:module';
import { chromium } from 'playwright';
import { createServer } from '../web/node_modules/vite/dist/node/index.js';
import { installAuditMember, auditNavigate } from './audit-session.mjs';
const require = createRequire(import.meta.url);
const { createAppHarness, member } = require('../backend/test-support/app-harness');
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const output = path.resolve(root, '.cache/audit-ui/groups-topic-tabs');
await fs.mkdir(output, { recursive: true });
const app = await createAppHarness();
app.seedUser(member('groups-tabs-audit'));
const server = await createServer({ root: path.join(root, 'web'), configFile: path.join(root, 'web/vite.config.js'), envDir: false,
  define: { 'import.meta.env.VITE_API_URL': JSON.stringify('/api'), 'import.meta.env.VITE_API_FALLBACK_URL': JSON.stringify('/fallback') },
  server: { host: '127.0.0.1', port: 5286, strictPort: false, proxy: Object.fromEntries(['api','fallback'].map(prefix => ['/'+prefix, { target: app.base, rewrite: value => value.replace(new RegExp('^/'+prefix), '') }])) } });
let browser, checks = 0;
const check = (condition, message) => { assert.ok(condition, message); checks++; };
try {
  await server.listen();
  browser = await chromium.launch({ channel: process.platform === 'win32' ? 'msedge' : undefined });
  for (const width of [1440, 820, 390, 320]) {
    const context = await browser.newContext({ viewport: {width, height: 950}, serviceWorkers: 'block' });
    const page = await context.newPage(); page.setDefaultTimeout(12000);
    const errors = [], requests = [];
    page.on('pageerror', error => errors.push(error.message));
    await context.route('**/*', async route => {
      const url = new URL(route.request().url());
      if (!['127.0.0.1','localhost'].includes(url.hostname)) return route.abort();
      const endpoint = url.pathname.replace(/^\/(api|fallback)/, '');
      if (/events|stream/.test(endpoint) && /^\/(api|fallback)\//.test(url.pathname)) return route.abort();
      if (endpoint === '/groups/categories') return route.fulfill({json:{categories:['Engineering','Design']}});
      if (endpoint === '/groups') return route.fulfill({json:{groups:Array.from({length:18},(_,i)=>({id:'community-'+i,name:'Community '+i,category:i%2?'Design':'Engineering',platform:i%2?'reddit':'uficonnect',isExternal:!!(i%2),members:100+i}))}});
      if (endpoint !== '/office/feed') return route.continue();
      const params = new URLSearchParams(url.searchParams); requests.push(params);
      const mode=params.get('mode'), source=params.get('source')||'uficonnect';
      return route.fulfill({json:{mode,nativeUficonnectIncluded:true,hasMore:false,posts:Array.from({length:30},(_,i)=>({id:mode+'-'+source+'-'+i,title:'Tabs audit '+mode+' '+i,content:'A community post about engineering.',source,topic:'Open Source',createdAt:new Date().toISOString(),groupId:'community-0',group:{id:'community-0',name:'Community 0'}}))}});
    });
    await installAuditMember(page,app,'groups-tabs-audit');
    const base=server.resolvedUrls.local[0];
    await auditNavigate(page,base+'?feed=feed');
    await page.getByText('Tabs audit feed 0',{exact:true}).waitFor();
    const trigger=page.getByRole('button',{name:'Filter feed by topic',exact:true});
    const popup=page.locator('.feed-topic-filter-popover');
    await trigger.click();
    check(await popup.getByRole('group',{name:'Filter categories',exact:true}).count()===0,'Home has topics only');
    check(await popup.getByRole('button',{name:'Apply topics',exact:true}).isVisible(),'Home keeps topic application');
    await trigger.click();
    await auditNavigate(page,base+'?feed=groups&groupScope=public');
    await page.getByText('Tabs audit groups 0',{exact:true}).waitFor();
    const toolbar=page.locator('.feed-group-filter-row');
    const groupTabs=page.getByRole('tablist',{name:'Group feeds',exact:true});
    const one=await groupTabs.getByRole('tab',{name:'Your groups',exact:true}).boundingBox();
    const two=await groupTabs.getByRole('tab',{name:'Public posts',exact:true}).boundingBox();
    check(Math.abs(one.y-two.y)<2,'Group tabs stay horizontal');
    await page.evaluate(()=>window.scrollTo(0,700)); await page.waitForTimeout(150);
    const pinned=await toolbar.boundingBox();
    const header=await page.locator('.global-app-header').boundingBox();
    check(pinned.y>=header.y+header.height-1 && pinned.y<header.y+header.height+25,'Group tabs remain pinned below header');
    await trigger.click();
    await popup.getByRole('button',{name:'Sources',exact:true}).click();
    await popup.getByRole('searchbox',{name:'Search sources',exact:true}).fill('Reddit');
    await popup.getByRole('group',{name:'Sources',exact:true}).getByRole('button',{name:'Reddit',exact:true}).click();
    await popup.getByRole('button',{name:'Topics',exact:true}).click();
    await popup.getByRole('searchbox',{name:'Search topics',exact:true}).fill('Open Source');
    await popup.getByRole('group',{name:'Topics',exact:true}).getByRole('button',{name:'Open Source',exact:true}).click();
    await popup.getByRole('button',{name:'Apply filters',exact:true}).click();
    await page.waitForTimeout(300);
    check(requests.some(q=>q.get('mode')==='groups'&&q.get('groupScope')==='public'&&q.get('source')==='reddit'&&q.get('topics')==='Open Source'),'Groups sends source and topic together');
    await trigger.click();
    await popup.getByRole('button',{name:'Sources (1)',exact:true}).click();
    check(await popup.getByRole('group',{name:'Sources',exact:true}).getByRole('button',{name:'Reddit',exact:true}).getAttribute('aria-pressed')==='true','Applied group source survives reopening');
    await popup.getByRole('button',{name:'Clear',exact:true}).click();
    await popup.getByRole('button',{name:'Apply filters',exact:true}).click();
    await page.waitForTimeout(250);
    check(!requests.at(-1).has('source')&&!requests.at(-1).has('topics'),'Clear removes both filters');
    await page.evaluate(()=>window.scrollTo(0,700));
    await page.screenshot({path:path.join(output,'groups-fixed-'+width+'.png')});
    await auditNavigate(page,base+'groups');
    await page.getByRole('button',{name:'Open Community 0',exact:true}).waitFor();
    const directory=page.locator('.group-directory-tabs');
    const bounds=await directory.getByRole('button').evaluateAll(buttons=>buttons.map(b=>({y:b.getBoundingClientRect().y})));
    check(bounds.every(b=>Math.abs(b.y-bounds[0].y)<2),'Directory groups use one horizontal row');
    await directory.getByRole('button',{name:'Open Community 17',exact:true}).scrollIntoViewIfNeeded();
    check(await directory.evaluate(el=>el.scrollLeft>0),'Horizontal group tabs scroll to last group');
    await page.getByRole('button',{name:'Filter discover groups by topic',exact:true}).click();
    const filterBounds=await page.getByRole('button',{name:'Filter discover groups by topic',exact:true}).boundingBox();
    check(filterBounds.x>=0&&filterBounds.x+filterBounds.width<=width,'Directory filter button is fully visible');
    const popupBounds=await popup.boundingBox();
    check(popupBounds.x>=0&&popupBounds.x+popupBounds.width<=width,'Directory source popup is fully visible');
    await popup.getByRole('button',{name:'Sources',exact:true}).click();
    await popup.getByRole('group',{name:'Sources',exact:true}).getByRole('button',{name:'Reddit',exact:true}).click();
    await popup.getByRole('button',{name:'Apply filters',exact:true}).click();
    check(await directory.getByRole('button').count()===9,'Directory filters groups by source');
    check(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth+1),'No viewport overflow');
    assert.deepEqual(errors,[]); checks++;
    await page.screenshot({path:path.join(output,'groups-horizontal-'+width+'.png')});
    await context.unrouteAll({behavior:'wait'}); await context.close();
    console.log('PASS: group filters and fixed horizontal tabs at '+width+'px');
  }
  console.log('PASS: '+checks+' checks');
}finally{await browser?.close();await server.close();await app.close();}
