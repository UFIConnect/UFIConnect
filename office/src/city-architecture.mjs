export function createBuildingLevels(district) {
  const metrics = new Map((district.metrics || []).map(item => [item.label, item]));
  return (CITY_BUILDING_LEVELS[district.id] || []).map((blueprint, index) => ({
    ...blueprint,
    id: `${district.id}-level-${index + 1}`,
    number: index + 1,
    metrics: blueprint.evidence.map(label => metrics.get(label) || { label, value: null }),
    breakdown: blueprint.showBreakdown ? district.breakdown || [] : [],
  }));
}
